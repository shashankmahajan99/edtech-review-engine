"""Page-aware review coverage, with explicit layout provenance and depth checks."""
from __future__ import annotations

import json
import math
import re
from dataclasses import dataclass
from pathlib import Path

from .docmodel import w

PROFILE = json.loads((Path(__file__).resolve().parents[2] / 'knowledge' / 'review_quality_profile.json').read_text(encoding='utf-8'))


@dataclass
class PageMap:
    method: str
    starts: dict[int, tuple[int, list[tuple[int, int]]]]
    words_before: dict[int, int]
    pages: list[int]

    def page_for(self, finding) -> int:
        if self.method == 'word_estimate':
            words = self.words_before.get(finding.paragraph.index, 0) + len(finding.paragraph.text[:finding.start].split())
            return min(max(self.pages), words // PROFILE['estimated_words_per_page'] + 1)
        page, breaks = self.starts.get(finding.paragraph.index, (1, []))
        for offset, after in breaks:
            if finding.start >= offset:
                page = after
        return page


def page_map(model) -> PageMap:
    cached = getattr(model, '_page_map_cache', None)
    if cached is not None:
        return cached
    result = _page_map(model)
    model._page_map_cache = result
    return result


def _word_page_map(model) -> PageMap | None:
    """Use Word's own paragraph page numbers so page counts match Word."""
    from .word_layout import word_paragraph_pages
    try:
        result = word_paragraph_pages(model.path)
    except Exception:
        return None
    if result is None:
        return None
    pages, total = result
    if len(pages) != len(model.paragraphs):
        return None
    starts = {para.index: (page, []) for para, page in zip(model.paragraphs, pages)}
    before = {}
    count = 0
    for para in model.paragraphs:
        before[para.index] = count
        count += len(para.words)
    # A trailing empty paragraph can make Word report a blank final page; it
    # cannot carry comments, so coverage targets content pages only.
    content = sorted({page for para, page in zip(model.paragraphs, pages) if para.text.strip()})
    return PageMap('word_rendered', starts, before, content or list(range(1, max(1, total) + 1)))


def _page_map(model) -> PageMap:
    # Word's own layout wins over any markers cached in the file: markers are
    # only written on Word's last save and go stale as soon as the document is
    # edited or generated by another library.
    word = _word_page_map(model)
    if word is not None:
        return word
    paras = [p for p in model.paragraphs if p.region != 'reviewer_note']
    rendered = any(p.element.find('.//' + w('lastRenderedPageBreak')) is not None for p in paras)
    explicit = any(p.element.find('.//' + w('br') + '[@' + w('type') + '="page"]') is not None
                   or p.element.find('./' + w('pPr') + '/' + w('pageBreakBefore')) is not None for p in paras)
    before = {}
    count = 0
    for para in paras:
        before[para.index] = count
        count += len(para.words)
    if not rendered and not explicit:
        pages = list(range(1, max(1, math.ceil(count / PROFILE['estimated_words_per_page'])) + 1))
        return PageMap('word_estimate', {}, before, pages)
    starts = {}
    page = 1
    used = set()
    for para in paras:
        if not rendered and para.element.find('./' + w('pPr') + '/' + w('pageBreakBefore')) is not None and used:
            page += 1
        start = page
        offset = 0
        breaks = []
        nodes = {n.element: n for n in para.nodes}
        for node in para.element.iter():
            if node in nodes:
                token = nodes[node]
                offset = token.end
                if token.text.strip():
                    used.add(page)
            if node.tag == w('lastRenderedPageBreak') and rendered or (
                    not rendered and node.tag == w('br') and node.get(w('type')) == 'page'):
                page += 1
                breaks.append((offset, page))
        starts[para.index] = (start, breaks)
    return PageMap('cached_rendered_markers' if rendered else 'explicit_breaks', starts, before, list(range(1, page + 1)))


def copied_comment_sentences(composed, endnote):
    from .segmenter import split_sentences
    normalized_letter = re.sub(r'\s+', ' ', ' '.join(endnote.paragraphs)).casefold()
    return [sentence.text for _, body in composed for sentence in split_sentences(body)
            if len(sentence.words) >= 8 and re.sub(r'\s+', ' ', sentence.text).casefold() in normalized_letter]


def assess(model, composed, endnote) -> dict:
    from .selection import RHETORICAL
    from .analysis import ANALYSIS, STATISTICS
    developmental_categories = RHETORICAL | {ANALYSIS, STATISTICS}
    copied_sentences = copied_comment_sentences(composed, endnote)
    pages = page_map(model)
    counts = {p: 0 for p in pages.pages}
    developmental = []
    for item, body in composed:
        page = pages.page_for(item.finding)
        counts[page] = counts.get(page, 0) + 1
        if item.category.split(' AND ')[0] in developmental_categories and item.finding.facts.get('kind') != 'strength':
            developmental.append((item, body))
    minimum = PROFILE['requested_comments_per_page']['min']
    under = [page for page, count in counts.items() if count < minimum]
    shallow = [item.finding.rule_id for item, body in developmental
               if len(body.split()) < PROFILE['developmental_comment_min_words']]
    messages = []
    strength_count = sum(item.finding.facts.get('kind') == 'strength' for item, _ in composed)
    if len(composed) >= 3 and strength_count > len(composed) / 2:
        messages.append('Most notes affirm strengths; check that meaningful revision opportunities have not been missed.')
    if under:
        messages.append(f"Coverage needs review on {len(under)} manuscript page(s): target 3–4 supported comments per page.")
    if shallow:
        messages.append(f"{len(shallow)} developmental comment(s) need a fuller explanation or revision step.")
    if copied_sentences:
        messages.append(f'{len(copied_sentences)} comment sentence(s) are repeated in the closing note; develop a separate revision plan.')
    bounds = PROFILE['reference_endnote_words']
    if not bounds['min'] <= endnote.word_count <= bounds['max']:
        messages.append(f"The closing note falls outside the reference range of {bounds['min']}–{bounds['max']} words; check its scope and development.")
    return {
        'layout_method': pages.method,
        'page_count': len(pages.pages),
        'page_count_is_estimate': pages.method == 'word_estimate',
        'target_comments_per_page': PROFILE['requested_comments_per_page'],
        'comments_by_page': [{'page': p, 'comments': c} for p, c in sorted(counts.items())],
        'undercovered_pages': under,
        'developmental_comments': len(developmental),
        'strength_comments': strength_count,
        'developmental_words_mean': round(sum(len(b.split()) for _, b in developmental) / len(developmental), 1) if developmental else 0,
        'shallow_developmental_rules': shallow,
        'endnote_words': endnote.word_count,
        'copied_comment_sentences_in_endnote': len(copied_sentences),
        'needs_review': bool(messages),
        'messages': messages,
    }
